"""
How often the shipped bot hallucinates, and how much of it reaches the reader.

This is a different question from the one eval/detection_ablation.py answers.
That harness scores detectors against 20 labelled cases with false claims
injected by hand: it says how good the judge is once a hallucination exists.
It says nothing about how often one exists, because the answers it grades were
never generated by this bot.

So this runs the real path. It imports main.py and calls the same
get_relevant_context and the same dated_prompt the Flask route calls, at the
same model and the same default temperature, then runs the same
hallucination.verify_answer over the result. Anything else would report
numbers describing a system nobody is running.

Three rates, and they are not equally important:

  1. Fabricated link rate - answers citing a URL absent from the context.
     Exact, no judge needed. This is the failure that actually costs a student
     a wasted trip.
  2. Unsupported claim rate - answers with at least one claim the grader says
     the context does not carry.
  3. Answering out of scope - the corpus has nothing, and the bot answered
     anyway instead of saying so. For a bot told to answer only from context,
     a substantive answer to an uncovered question is a hallucination even
     when the fact is true.

And the number that matters more than any of them:

  4. Unflagged rate - of the answers that hallucinated, how many carried no
     caution. A caught hallucination is a warning label. An uncaught one is
     the actual product failure, and it is the only one a reader cannot see.

Answers are sampled at the production temperature, which is the default 1.0,
so these are rates with real variance rather than fixed properties. Each
question runs VRHS_REPEATS times (default 2) and every trial counts
separately.

    OPENAI_API_KEY=... python eval/hallucination_rate.py
    VRHS_REPEATS=3 python eval/hallucination_rate.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Importing main starts a warm-up thread that is useful in the app and just
# noise here.
os.environ.setdefault("VRHS_NO_WARM", "1")

import config  # noqa: E402
import hallucination  # noqa: E402
import main  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "fixtures", "questions.json")
RESULTS = os.path.join(HERE, "results", "hallucination_rate.txt")
# Raw trials are written next to the report so a metric can be redefined and
# recomputed without paying for 200 more API calls. That is not hypothetical:
# the first version of this harness counted the retrieval gate's correct
# "nothing covers this" notice on out-of-scope refusals as a spurious caution,
# reported a 36% over-warning rate, and had to be run again to correct it.
TRIALS = os.path.join(HERE, "results", "hallucination_rate_trials.json")

REPEATS = int(os.getenv("VRHS_REPEATS", "2"))

# Deciding whether an answer abstained is a judgement call that a keyword list
# gets wrong in both directions: "I don't have the exact time" inside an
# otherwise full answer is not an abstention, and an abstention phrased as
# "that isn't something the school pages cover" contains none of the obvious
# markers. A small model classifies it instead.
#
# This is a separate task from grading groundedness, and it never sees the
# context, so it cannot ratify the generator's mistakes the way a same-model
# grader would.
CLASSIFIER_MODEL = "gpt-4o-mini"

CLASSIFIER_PROMPT = """You are labelling one chatbot reply.

Decide whether the reply actually answers the QUESTION, or whether it declines
because it does not have the information.

Label "substantive" when the reply states facts that answer the question, even
partially, and even if it also suggests contacting the school.

Label "declined" when the reply's substance is that it does not know, does not
have that information, or that the topic is not covered, and it offers no
facts answering the question. A reply that only redirects the reader to the
staff directory or the front office is declined.

Reply with JSON only: {"verdict": "substantive"} or {"verdict": "declined"}"""


def classify_answer(client, question, answer):
    """True when the reply answered, False when it declined."""
    response = client.chat.completions.create(
        model=CLASSIFIER_MODEL,
        temperature=0,
        response_format={"type": "json_object"},
        messages=[{
            "role": "system",
            "content": CLASSIFIER_PROMPT
        }, {
            "role": "user",
            "content": "QUESTION:\n" + question + "\n\nREPLY:\n" + answer
        }])
    parsed = json.loads(response.choices[0].message.content)
    return parsed.get("verdict") == "substantive"


def answer_once(question):
    """One trip through the production answer path, minus the HTTP streaming.

    Uses main.get_relevant_context and main.dated_prompt rather than
    reimplementing retrieval, so this cannot silently drift from what the
    route does.
    """
    context, stats, sources = main.get_relevant_context(question)

    response = main.client.chat.completions.create(
        model=config.CHAT_MODEL,
        messages=[{
            "role": "system",
            "content": main.dated_prompt()
        }, {
            "role": "user",
            "content": "Context:\n" + context + "\n\nQuestion: " + question
        }])
    answer = response.choices[0].message.content or ""

    verdict = hallucination.verify_answer(main.client, answer, context, stats)
    return answer, context, verdict


def evaluate():
    fixtures = json.load(open(FIXTURES, encoding="utf-8"))
    client = main.client
    trials = []

    for scope in ("answerable", "out_of_scope"):
        for case in fixtures[scope]:
            question = case["question"]
            for run in range(REPEATS):
                answer, context, verdict = answer_once(question)
                substantive = classify_answer(client, question, answer)

                # What went wrong, if anything.
                faults = []
                if verdict.bad_links:
                    faults.append("link")
                if verdict.unsupported:
                    faults.append("claim")
                if scope == "out_of_scope" and substantive:
                    faults.append("answered-uncovered")

                trials.append({
                    "scope": scope,
                    "question": question,
                    "run": run,
                    "answer": answer,
                    "substantive": substantive,
                    "faults": faults,
                    "flagged": bool(verdict.notice_points()),
                    "notice": verdict.notice_points(),
                    "retrieval_level": verdict.retrieval_level,
                    "retrieval_top": verdict.retrieval_top,
                    "bad_links": verdict.bad_links,
                    "unsupported": verdict.unsupported,
                })
                mark = ",".join(faults) if faults else "clean"
                print("  [%s] %-44s run%d %s"
                      % (scope[:3], question[:44], run, mark))

    return trials


def pct(count, total):
    return "%.1f%%" % (100.0 * count / total) if total else "n/a"


def report(trials, out):
    def emit(line=""):
        print(line)
        out.append(line)

    answerable = [t for t in trials if t["scope"] == "answerable"]
    uncovered = [t for t in trials if t["scope"] == "out_of_scope"]

    emit("trials: %d (%d answerable, %d out of scope), %d run(s) per "
         "question, %s at production temperature"
         % (len(trials), len(answerable), len(uncovered), REPEATS,
            config.CHAT_MODEL))
    emit()

    emit("%-44s%10s%8s%10s" % ("rate", "count", "of", ""))
    emit("-" * 72)

    link_bad = [t for t in trials if "link" in t["faults"]]
    claim_bad = [t for t in trials if "claim" in t["faults"]]
    answered_uncovered = [t for t in uncovered
                          if "answered-uncovered" in t["faults"]]
    declined_answerable = [t for t in answerable if not t["substantive"]]

    rows = [
        ("fabricated link", len(link_bad), len(trials)),
        ("unsupported claim", len(claim_bad), len(trials)),
        ("answered an uncovered question", len(answered_uncovered),
         len(uncovered)),
        ("declined a question the corpus covers", len(declined_answerable),
         len(answerable)),
    ]
    for label, count, total in rows:
        emit("%-44s%10d%8d%10s" % (label, count, total, pct(count, total)))

    emit()
    faulty = [t for t in trials if t["faults"]]
    unflagged = [t for t in faulty if not t["flagged"]]

    # Over-warning is counted on answerable questions only. An out-of-scope
    # question that the bot declines still earns "nothing on the VRHS site
    # covers this" from the retrieval gate, and that notice is correct and
    # wanted - it tells the reader the reply is not sourced from school pages.
    # Counting it as a spurious caution, which an earlier version of this
    # report did, put the gate working exactly as designed into a column
    # labelled noise and read as a 36% over-warning rate.
    clean_flagged = [t for t in answerable
                     if not t["faults"] and t["flagged"]]

    emit("%-44s%10s%8s%10s" % ("what the reader sees", "count", "of", ""))
    emit("-" * 72)
    emit("%-44s%10d%8d%10s" % ("trials with any fault", len(faulty),
                               len(trials), pct(len(faulty), len(trials))))
    emit("%-44s%10d%8d%10s" % ("  of those, flagged to the reader",
                               len(faulty) - len(unflagged), len(faulty),
                               pct(len(faulty) - len(unflagged), len(faulty))))
    emit("%-44s%10d%8d%10s" % ("  of those, reached reader unflagged",
                               len(unflagged), len(faulty),
                               pct(len(unflagged), len(faulty))))
    emit("%-44s%10d%8d%10s" % ("answerable, no fault, warned anyway",
                               len(clean_flagged), len(answerable),
                               pct(len(clean_flagged), len(answerable))))

    if unflagged:
        emit()
        emit("unflagged faults, the ones that matter:")
        for t in unflagged:
            emit("  [%s] %s" % (",".join(t["faults"]), t["question"]))
            emit("      retrieval=%s top=%s"
                 % (t["retrieval_level"], t["retrieval_top"]))
            if t["bad_links"]:
                emit("      invented: %s" % t["bad_links"])
            if t["unsupported"]:
                emit("      unsupported: %s" % t["unsupported"][:2])

    if clean_flagged:
        emit()
        emit("cautions on answers with no detected fault (over-warning):")
        for t in clean_flagged:
            emit("  %s" % t["question"][:60])
            emit("      %s" % t["notice"])

    if declined_answerable:
        emit()
        emit("refused a question the corpus covers (the opposite failure):")
        for t in declined_answerable:
            emit("  %s" % t["question"])
            emit("      retrieval=%s top=%s"
                 % (t["retrieval_level"], t["retrieval_top"]))

    emit()
    emit("Read with care: at this sample size a single trial moves any rate "
         "by several points, and")
    emit("temperature 1.0 means a rerun will not reproduce these exactly. "
         "The out-of-scope set is")
    emit("also blunt - questions the site plainly does not cover. Subtle "
         "near-misses, where the")
    emit("corpus half answers, are the harder untested case.")


if __name__ == "__main__":
    if not os.getenv("OPENAI_API_KEY"):
        sys.exit("OPENAI_API_KEY not set")

    results = evaluate()
    print()
    lines = []
    report(results, lines)

    os.makedirs(os.path.dirname(RESULTS), exist_ok=True)
    with open(RESULTS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(TRIALS, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)
    print("\nwritten to %s and %s"
          % (os.path.relpath(RESULTS), os.path.relpath(TRIALS)))
